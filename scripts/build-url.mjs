import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const dataPath = resolve(root, 'src/data/data.json')
const outPath = resolve(root, 'src/data/data.js')

const KEYWORD_HINTS = ['software', 'engineer', 'developer', 'backend', 'engineering', 'senior']

function decodeSafe(raw) {
  try {
    return decodeURIComponent(raw.replace(/\+/g, ' '))
  } catch {
    return raw
  }
}

function containsKeyword(decoded) {
  const s = decoded.toLowerCase()
  return KEYWORD_HINTS.some((h) => s.includes(h))
}

function transformPart(part) {
  return part
    .split('&')
    .map((pair) => {
      const eq = pair.indexOf('=')
      if (eq === -1) return pair
      const k = pair.slice(0, eq)
      const rawV = pair.slice(eq + 1)
      if (!rawV) return pair
      if (!containsKeyword(decodeSafe(rawV))) return pair
      return `${k}={query}`
    })
    .join('&')
}

function templateUrl(url) {
  if (!url) return url
  const hashIndex = url.indexOf('#')
  const base = hashIndex === -1 ? url : url.slice(0, hashIndex)
  const frag = hashIndex === -1 ? '' : url.slice(hashIndex + 1)

  const qIndex = base.indexOf('?')
  const path = qIndex === -1 ? base : base.slice(0, qIndex)
  const query = qIndex === -1 ? '' : base.slice(qIndex + 1)

  const newQuery = query ? transformPart(query) : ''
  const newFrag = frag ? transformPart(frag) : ''

  let result = path
  if (newQuery) result += `?${newQuery}`
  if (newFrag) result += `#${newFrag}`
  return result
}

if (!existsSync(dataPath)) {
  console.error(
    `Missing ${dataPath}. data.js is the hand-maintained source of truth; ` +
      'this script only regenerates it from a data.json export. Nothing written.',
  )
  process.exit(1)
}

const data = JSON.parse(readFileSync(dataPath, 'utf8'))
let templated = 0
let skipped = 0

const categories = data.categories.map((cat) => ({
  ...cat,
  companies: cat.companies.map((c) => {
    if (!c.careersUrl) return { ...c }
    const url = c.careersUrl
    const templatedUrl = templateUrl(url)
    if (templatedUrl.includes('{query}')) templated++
    else skipped++
    return { ...c, careersUrl: templatedUrl }
  }),
}))

const js = `// Autogenerated from data.json by scripts/build-url.mjs\n// Do not edit directly; regenerate with: node scripts/build-url.mjs\nexport const categories = ${JSON.stringify(categories, null, 2)}\n`

writeFileSync(outPath, js)
console.log(`Converted data.json → data.js (${templated} URLs templated, ${skipped} kept static)`)
